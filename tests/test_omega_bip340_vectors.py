class Bip340VectorTests(unittest.TestCase):
    def test_vector_count(self):
        self.assertEqual(len(VECTORS), 19)

    def test_pubkey_generation(self):
        for index, sk, pk, _aux, _msg, _sig, _ok, _comment in VECTORS:
            if sk is None:
                continue
            with self.subTest(index=index):
                self.assertEqual(
                    bip340.pubkey_gen(bytes.fromhex(sk)).hex(), pk.lower()
                )

    def test_signing_byte_exact(self):
        for index, sk, _pk, aux, msg, sig, _ok, _comment in VECTORS:
            if sk is None:
                continue
            with self.subTest(index=index):
                self.assertEqual(
                    bip340.sign(
                        bytes.fromhex(msg),
                        bytes.fromhex(sk),
                        bytes.fromhex(aux),
                    ).hex(),
                    sig.lower(),
                )

    def test_verification_results(self):
        for index, _sk, pk, _aux, msg, sig, expected, comment in VECTORS:
            with self.subTest(index=index, comment=comment):
                self.assertEqual(
                    bip340.verify(
                        bytes.fromhex(msg),
                        bytes.fromhex(pk),
                        bytes.fromhex(sig),
                    ),
                    expected,
                )

    def test_sign_rejects_bad_secret_key(self):
        with self.assertRaises(bip340.InvalidKeyError):
            bip340.sign(b"m", b"\x00" * 32, b"\x00" * 32)
        with self.assertRaises(bip340.InvalidKeyError):
            bip340.pubkey_gen(bytes.fromhex("FF" * 32))

    def test_verify_fails_closed_on_bad_lengths(self):
        self.assertFalse(bip340.verify(b"m", b"\x00" * 31, b"\x00" * 64))
        self.assertFalse(bip340.verify(b"m", b"\x00" * 32, b"\x00" * 63))


if __name__ == "__main__":
    unittest.main()
